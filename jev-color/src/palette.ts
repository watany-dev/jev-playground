export type Color = {
  /** 色名。choice の criteria のキーであり、そのまま回答のキーになる。 */
  readonly name: string;
  /** `#RRGGBB`。画面表示と、確率で混ぜた「期待色」の計算に使う。 */
  readonly hex: string;
  readonly hint: string;
  readonly family: Family;
};

function build(): readonly Color[] {
  const groups: [Family, Entry[]][] = [
    ['red', RED], ['pink', PINK], ['orange', ORANGE], ['brown', BROWN],
    ['yellow', YELLOW], ['yellowgreen', YELLOWGREEN], ['green', GREEN],
    ['bluegreen', BLUEGREEN], ['blue', BLUE], ['navy', NAVY],
    ['purple', PURPLE], ['mono', MONO],
  ];
  return groups.flatMap(([family, entries]) =>
    entries.map(([name, hex, hint]) => ({ name, hex: `#${hex}`, hint, family })),
  );
}

/** 255色。Jev の choice 1問に入る上限であり、この数がこのサンプルの主題である。 */
export const COLORS: readonly Color[] = build();

/** choice の候補数の上限。これを超える criteria は Jev が受け付けない。 */
export const MAX_CHOICES = 255;

export const BY_NAME: ReadonlyMap<string, Color> = new Map(COLORS.map(c => [c.name, c]));
